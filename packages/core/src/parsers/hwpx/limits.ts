/**
 * HWPX 해석의 자원 상한.
 *
 * HWPX 는 사용자가 올린 파일이고(.hwpx 직접, .hwp 의 rhwp 변환 결과, ZIP 을
 * .hwp 로 저장한 파일), REST·MCP 서버는 변환을 같은 프로세스에서 동기로 돈다.
 * 작은 파일 하나가 메모리·CPU 를 무한정 쓰지 못하게, 실측한 실물 최대치에
 * 넉넉한 여유를 둔 값으로 묶는다. 수치 근거는 2026-10-03 비공개 표본 5건
 * (HWPX 1건 + .hwp 4건의 rhwp 변환 결과) 실측이다.
 */

const MIB = 1024 * 1024;

/**
 * ZIP 항목 수 상한. 실물 최대 35개. 그림 한 장이 항목 하나라 그림이 많은
 * 문서도 수천 개를 넘기 어렵다. 풀지 않는 항목도 목록은 읽으므로 그 비용을
 * 묶는 안전장치다 (kordoc 의 500 은 그림 500장 문서를 거부해 쓰지 않았다).
 */
export const MAX_ZIP_ENTRIES = 10_000;

/**
 * 풀어서 해석할 XML(본문·머리·목차) 합계 상한. 실물 최대 6.2MB 의 약 5배 —
 * 140쪽 문서가 4.3MB 라 1,000쪽 안팎까지 받는다.
 *
 * XML 은 객체 트리로 펼쳐지며 작은 문단이 빽빽하면 힙을 원문의 수십 배 쓴다
 * (2026-10-03 실측: 64MB 섹션 파싱만 힙 2.78GB, 120MB 는 기본 힙에서 프로세스가
 * 잡을 수 없는 OOM 으로 죽었다). 128MB 였던 값을 낮췄다 — 30MB 의 최악 모양
 * (한 글자 문단 32만 개)이 4초·RSS 1.1GB 로 끝난다.
 */
export const MAX_XML_BYTES = 32 * MIB;

/**
 * 풀어 쓰는 항목(XML + 그림) 합계 상한. 실물 최대 128.5MB(대형 BMP 첨부).
 * .hwp 사전 검사의 문서 합계 상한(512MB)과 같게 둔다 — rhwp 가 만든 HWPX 는
 * 원본 HWP 의 풀린 크기와 거의 같아서(실측 128.4MB vs 127.7MB) 더 낮추면
 * 사전 검사를 통과한 .hwp 를 여기서 다시 거부하게 된다. 서버 업로드 상한
 * 50MB 문서가 실물 압축비(6.4)로 풀려도(≈320MB) 들어간다.
 */
export const MAX_INFLATED_BYTES = 512 * MIB;

/**
 * 표 하나의 열 수 상한. 실물 최대 42열 — 256열 표는 A3 가로에도 못 싣는다.
 * 병합 칸(colSpan)은 빈 칸으로 펼쳐지므로, 손상·악성 파일의 colSpan 하나가
 * 표를 수만 열로 부풀리지 못하게 막는다.
 */
export const MAX_TABLE_COLS = 256;

/**
 * 문서 전체 병합 칸 상한 — 표를 격자로 펼칠 때 셀(`<hp:tc>`)이 아니라 병합·
 * 행 길이 보정으로 생기는 칸(←·↑·빈칸)의 합계. 실제 셀은 XML 크기에 비례해
 * 이미 `MAX_XML_BYTES`로 묶이지만, 병합 칸은 입력 1바이트당 수십 칸까지 불어나
 * (빈 `<tr>` 하나가 열 수만큼의 ↑ 칸이 된다) 따로 센다. 실물 문서 하나의
 * 병합·빈 칸은 많아야 3,666칸(빈 셀까지 센 상한)으로 그 55배이고, 다 채워도
 * 변환 1~2초·출력 1MB 안팎이다 (100만 칸은 8초·4MB 로 실측돼 낮췄다).
 */
export const MAX_MERGED_CELLS = 200_000;
